"""Generate the app's spoken phrases as MP3 clips with a neural Hebrew voice.

Usage (from the project folder):
    python3 -m venv .venv && .venv/bin/pip install edge-tts
    .venv/bin/python tools/make_voice.py            # default voice: Hila
    .venv/bin/python tools/make_voice.py he-IL-AvriNeural

Writes web/voice/f/*.mp3 (addressing a girl), web/voice/m/*.mp3 (addressing a boy)
and web/js/phrases.js (the same texts, used for speech bubbles and the parent recording screen).
To use a cloned voice (e.g. ElevenLabs), generate files with the same names into web/voice/f and web/voice/m.
"""
import asyncio, json, os, sys
import edge_tts

VOICE = sys.argv[1] if len(sys.argv) > 1 else "he-IL-HilaNeural"
ROOT = os.path.join(os.path.dirname(__file__), "..", "web")

COLORS = {"do": "האדום", "re": "הכתום", "mi": "הצהוב", "fa": "הירוק", "sol": "התכלת", "la": "הכחול", "si": "הסגול"}

# key: (girl text, boy text)
P = {
    "hello":   ("היי! אני נוטי. בואי ננגן ביחד!", "היי! אני נוטי. בוא ננגן ביחד!"),
    "p1": ("יופי!", "יופי!"),
    "p2": ("מעולה!", "מעולה!"),
    "p3": ("וואו!", "וואו!"),
    "p4": ("כל הכבוד!", "כל הכבוד!"),
    "p5": ("מדהים!", "מדהים!"),
    "p6": ("את אלופה!", "אתה אלוף!"),
    "p7": ("בדיוק ככה!", "בדיוק ככה!"),
    "p8": ("איזה כישרון!", "איזה כישרון!"),
    "streak":  ("וואו, איזה רצף! את על האש!", "וואו, איזה רצף! אתה על האש!"),
    "almost":  ("כמעט! נסי שוב", "כמעט! נסה שוב"),
    "watch":   ("צפי בי קודם!", "צפה בי קודם!"),
    "yourturn": ("עכשיו תורך! לחצי על האורגן, איפה שהסימן מראה", "עכשיו תורך! לחץ על האורגן, איפה שהסימן מראה"),
    "listen":  ("הקשיבי טוב...", "הקשב טוב..."),
    "echo_you": ("עכשיו את!", "עכשיו אתה!"),
    "stars3":  ("וואו! שלושה כוכבים! את מדהימה!", "וואו! שלושה כוכבים! אתה מדהים!"),
    "stars2":  ("כל הכבוד! ניגנת יפה מאוד!", "כל הכבוד! ניגנת יפה מאוד!"),
    "stars1":  ("יפה מאוד! בפעם הבאה יהיה עוד יותר טוב!", "יפה מאוד! בפעם הבאה יהיה עוד יותר טוב!"),
    "gift":    ("קיבלת מתנה! לחצי עליה", "קיבלת מתנה! לחץ עליה"),
    "sticker": ("מדבקה חדשה לאלבום!", "מדבקה חדשה לאלבום!"),
    "daily":   ("יש לך מתנה של היום!", "יש לך מתנה של היום!"),
    "break":   ("זמן להפסקה קטנה! ניגנת נהדר. נתראה בפעם הבאה!", "זמן להפסקה קטנה! ניגנת נהדר. נתראה בפעם הבאה!"),
    "noinput": ("אני לא שומע את האורגן. בקשי עזרה מאבא או מאמא", "אני לא שומע את האורגן. בקש עזרה מאבא או מאמא"),
    "jar":     ("כל כוכב ממלא את הצנצנת!", "כל כוכב ממלא את הצנצנת!"),
    "free":    ("נגני מה שבא לך!", "נגן מה שבא לך!"),
}
for k, c in COLORS.items():
    P["find_" + k] = (f"איפה {c}? לחצי על {c} באורגן!", f"איפה {c}? לחץ על {c} באורגן!")
    P["now_" + k] = (f"עכשיו {c}!", f"עכשיו {c}!")


async def main():
    for g, idx in (("f", 0), ("m", 1)):
        out = os.path.join(ROOT, "voice", g)
        os.makedirs(out, exist_ok=True)
        for key, texts in P.items():
            await edge_tts.Communicate(texts[idx], VOICE, rate="-4%", pitch="+12Hz").save(os.path.join(out, key + ".mp3"))
            print(g, key)
    with open(os.path.join(ROOT, "js", "phrases.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/make_voice.py — spoken phrase texts [girl, boy].\n")
        f.write("window.PHRASES = " + json.dumps(P, ensure_ascii=False, indent=1) + ";\n")

asyncio.run(main())
